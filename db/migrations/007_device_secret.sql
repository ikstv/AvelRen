-- Installation secret на пристрій.
--
-- До цієї міграції `device_id` (UUID) працював як єдиний bearer-credential:
-- знаєш заголовок X-Device-Id — керуєш підписками. Проблема була не в UUID, а
-- в тому, як його можна отримати: POST /devices повертав існуючий id, якщо в
-- запиті ішов уже відомий FCM-токен. А FCM-токен — не секрет: він живе на
-- клієнті, в логах Google, у крешах. Атака: знав чужий токен → отримав чужий
-- device_id → маніпулював чужими підписками; якщо жертва is_admin — читав
-- /admin/telemetry (аудит AUTH-1).
--
-- Виправлення двошарове:
--   1) POST /devices більше НЕ віддає id старого пристрою при співпадінні
--      токена (це робиться в коді, а не тут).
--   2) Кожен пристрій отримує окремий secret — 32 випадкові байти. У БД
--      зберігаємо лише SHA-256 hex digest секрета. Перевірка йде на рівні
--      Python через hmac.compare_digest, constant-time.
--
-- Чому НЕ bcrypt/pgcrypto:
--   Bcrypt має сенс для паролів, які люди обирають слабкими. Наш secret — 32
--   випадкові байти (256 бітів ентропії); offline-перебір хешу нереальний
--   навіть із SHA-256. Натомість bcrypt cost=10 виконується у PostgreSQL за
--   ~100 мс, і оскільки _device() викликається на КОЖЕН захищений запит,
--   зловмисник із власним валідним UUID міг би влаштувати CPU-DoS на БД,
--   сиплючи невірні secrets. SHA-256 усуває цей вектор, не втрачаючи
--   security для нашого типу секрета.
--
-- Формат: hex-рядок (64 символи), NULL для старих пристроїв без secret.
-- Пристрій без secret не проходить перевірку і мусить перереєструватись.

ALTER TABLE devices
    ADD COLUMN IF NOT EXISTS secret_hash text;

-- Documented residual risk (NEW-AUTH-3): POST /devices з відомим FCM-токеном
-- переносить токен на нову installation. Це не account takeover (id/secret
-- пари старої installation лишаються при жертві), але це availability attack
-- — жертва перестає отримувати push, доки не переустановить застосунок і не
-- зареєструється знову. Повне рішення (challenge-via-FCM) винесене в окремий
-- PR, бо потребує клієнт-серверного round-trip до прив'язки токена.

-- В цій БД зараз немає жодного продакшн-пристрою з активною підпискою (єдиний
-- встановлений клієнт власника — без підписок). Тож старі пристрої без
-- secret_hash не потрібно масово перереєстровувати: наступний write-запит з
-- 401 просто змусить клієнта створити нову installation.

def surge_location(checkpoint_id: int, title: str) -> str:
    place = _PLACES.get(checkpoint_id)
    if place is None:
        return f"на КПП «{title}»"
    lower = title.casefold()
    if "порожніх" in lower:
        suffix = " для порожніх вантажівок"
    elif "товари 1-24" in lower:
        suffix = " для товарів груп від першої до двадцять четвертої"
    elif "до ≤ 7,5" in title:
        suffix = " для вантажівок від трьох з половиною до семи з половиною тонн"
    elif "≤ 3,5" in title:
        suffix = " для вантажівок до трьох з половиною тонн"
    elif "≤ 7,5" in title:
        suffix = " для вантажівок до семи з половиною тонн"
    elif "< 7,5" in title:
        suffix = " для вантажівок менше семи з половиною тонн"
    else:
        suffix = ""
    return place + suffix


def surge_body(kind: str, checkpoint_id: int, title: str) -> str:
    starts = {
        "surge_forecast": "Можливий початок масової реєстрації",
        "surge_started": "Почалось зростання черги",
    }
    if kind not in starts:
        raise ValueError("unknown surge kind")
    return f"{starts[kind]} {surge_location(checkpoint_id, title)}"
